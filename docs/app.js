import { API_BASE } from './config.js';
const byId = id => document.getElementById(id);
const state = { songs: [], lastAction: 'mood', previousId: null, working: false, aiAvailable: false };
const apiBase = API_BASE.replace(/\/+$/, '');
const feedback = (message, isError = false) => {
  const el = byId('feedback');
  el.textContent = message;
  el.classList.toggle('error', isError);
};
function tag(text,klass='tag'){const span=document.createElement('span');span.className=klass;span.textContent=text;return span;}
function drawTags(p){
  const container=byId('analysis-tags');const nodes=[];
  for(const [label,key] of [['Mood','moods'],['Genre','genres'],['Scene','scenes'],['Instruments','instruments']]){
    for(const value of p[key]||[]){const wrapper=document.createElement('span');wrapper.className='analysis-tag';const name=document.createElement('span');name.textContent=label;wrapper.append(name,document.createTextNode(value));nodes.push(wrapper);}
  }
  if(p.energy&&p.energy!=='any')nodes.push(tag(`Energy · ${p.energy}`,'analysis-tag'));
  if(!nodes.length)nodes.push(tag('未辨識到明確標籤，採用隨機探索','analysis-tag'));
  container.replaceChildren(...nodes);
}
function render(data){
  const s=data.song;
  byId('song-name').textContent=s.title;
  byId('artist').textContent=s.artist;
  byId('tags').replaceChildren(...[...s.genre,...s.mood.slice(0,2)].map(x=>tag(x)));
  byId('result-source').textContent='LIVE LLM GENERATION';
  byId('review-source').textContent='GENERATED BY LLM';
  byId('analysis-source').textContent='LLM STRUCTURED OUTPUT';
  byId('score').textContent=data.matchScore===null?'SURPRISE PICK':`標籤相似度 ${data.matchScore}%`;
  byId('review-text').textContent=data.review;
  byId('reason-text').textContent=data.reason;
  byId('prompt-text').textContent=data.imagePrompt;
  byId('analysis-explanation').textContent=data.analysis.explanation||'依標籤進行規則式匹配。';
  drawTags(data.analysis);
  const palette=s.color_palette||[];
  for(let i=0;i<3;i++)if(/^#[a-fA-F0-9]{6}$/.test(palette[i]||''))byId('cover').style.setProperty(`--tone${i+1}`,palette[i]);
  byId('youtube-link').href=`https://www.youtube.com/watch?v=${encodeURIComponent(s.youtube_id)}`;
  const iframe=document.createElement('iframe');iframe.title=`${s.artist} - ${s.title} YouTube 播放器`;
  iframe.src=`https://www.youtube-nocookie.com/embed/${encodeURIComponent(s.youtube_id)}?rel=0`;
  iframe.loading='eager';iframe.referrerPolicy='strict-origin-when-cross-origin';
  iframe.setAttribute('allow','accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture; web-share');iframe.setAttribute('allowfullscreen','');
  byId('player').replaceChildren(iframe);
  byId('results').hidden=false;
  state.previousId=s.id;
  byId('results').scrollIntoView({behavior:window.matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth',block:'start'});
}
async function run(action) {
  if (state.working) return;
  if (!state.aiAvailable) {feedback('AI 後端尚未連線：先按照 README 設定 Cloudflare Worker、API Key 和 docs/config.js。',true);return;}
  const mood = byId('mood-text').value.trim();
  if (action === 'mood' && !mood) {feedback('請先輸入心情，或使用「隨機抽歌」。',true);byId('mood-text').focus();return;}
  if (!state.songs.length) {feedback('歌曲資料庫尚未載入。',true);return;}
  state.working = true;
  state.lastAction = action;
  for (const id of ['recommend-btn','random-btn','again-btn']) byId(id).disabled = true;
  feedback('LLM 正在解析情緒、選歌並生成微型樂評與圖片 Prompt……');
  try {
    const response = await fetch(`${apiBase}/recommend`, {
      method: 'POST', headers: {'Content-Type':'application/json'},
      body:JSON.stringify({mode:action,mood,previousId:state.previousId})
    });
    let data;
    try {data=await response.json();}
    catch {throw new Error('AI 服務回傳格式有誤，請檢查 Cloudflare Workers Logs。');}
    if (!response.ok) throw new Error(data.error || `AI 服務錯誤（HTTP ${response.status}）`);
    render(data);
    feedback('完成！微型樂評與圖片 Prompt 都由 LLM 即時生成。');
  } catch(e) {feedback(e?.message || '推薦失敗，請稍後再試。',true);}
  finally {state.working=false;for (const id of ['recommend-btn','random-btn','again-btn']) byId(id).disabled = !state.aiAvailable;}
}
async function init(){
  try {
    const response = await fetch('./data/songs.json', {cache:'no-store'});
    if (!response.ok) throw new Error('歌曲資料無法載入');
    const songs = await response.json();
    if (!Array.isArray(songs) || !songs.length) throw new Error('資料庫格式錯誤');
    state.songs=songs;byId('library-count').textContent=songs.length;
  } catch(e) {feedback('網站歌曲資料載入失敗，請確認 docs/data/songs.json。',true);}
  if (!apiBase || !/^https:\/\/[^/]+$/.test(apiBase) || apiBase.includes('REPLACE')) {
    byId('connection-status').textContent = '◌ AI 尚未連接';
    feedback('請先在 docs/config.js 填入 Cloudflare Worker 的公開 HTTPS 網址。',true);
    return;
  }
  try {
    const response = await fetch(`${apiBase}/status`, {signal:AbortSignal.timeout(6000)});
    if (!response.ok) throw new Error('服務未就緒');
    const data = await response.json();
    state.aiAvailable=!!data.configured;
    byId('connection-status').textContent = state.aiAvailable ? '✦ AI 已連線' : '△ AI 後端尚未設定完成';
    feedback(state.aiAvailable ? '已連接真正的 LLM；現在可以輸入心情或隨機抽歌。' : '請在 Cloudflare Worker 設定 ALLOWED_ORIGIN 以及 OPENAI_API_KEY。',!state.aiAvailable);
    for (const id of ['recommend-btn','random-btn','again-btn']) byId(id).disabled=!state.aiAvailable;
  } catch(e) {
    byId('connection-status').textContent='◌ AI 無法連線';
    feedback('無法連接 Worker：請檢查 config.js 網址、Workers 部署和 ALLOWED_ORIGIN。',true);
  }
}
for (const id of ['recommend-btn','random-btn','again-btn']) byId(id).disabled=true;
byId('recommend-btn').addEventListener('click',()=>run('mood'));
byId('random-btn').addEventListener('click',()=>run('random'));
byId('again-btn').addEventListener('click',()=>run(state.lastAction));
byId('mood-text').addEventListener('input',()=>{byId('char-count').textContent=`${byId('mood-text').value.length} / 220`;});
for (const chip of document.querySelectorAll('[data-mood]')) chip.addEventListener('click',()=>{
  byId('mood-text').value=chip.dataset.mood;
  byId('mood-text').dispatchEvent(new Event('input'));
  feedback('已填入心情，按「依心情找歌」開始 AI 推薦。');
});
byId('copy-prompt').addEventListener('click',async()=>{
  const value=byId('prompt-text').textContent;
  try {await navigator.clipboard.writeText(value);byId('copy-prompt').textContent='✓ 已複製';}
  catch {byId('copy-prompt').textContent='請手動選取文字複製';}
  setTimeout(()=>{byId('copy-prompt').textContent='複製 Prompt ⧉';},1800);
});
init();

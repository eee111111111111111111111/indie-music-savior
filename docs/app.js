import { API_BASE } from './config.js';
const byId=id=>document.getElementById(id);
const state={songs:[],lastAction:'mood',previousId:null,working:false,aiAvailable:false,llmAvailable:false,imageAvailable:false,lastResult:null,coverWorking:false};
const apiBase=String(API_BASE||'').replace(/\/+$/,'');
const covers=new Map();
const feedback=(message,isError=false)=>{const el=byId('feedback');el.textContent=message;el.classList.toggle('error',isError);};
const tag=(text,klass='tag')=>{const node=document.createElement('span');node.className=klass;node.textContent=text;return node;};
function drawTags(p){
  const container=byId('analysis-tags'),nodes=[];
  for(const [label,key] of [['Mood','moods'],['Genre','genres'],['Scene','scenes'],['Instruments','instruments']]){
    for(const value of p[key]||[]){const node=document.createElement('span');node.className='analysis-tag';const name=document.createElement('span');name.textContent=label;node.append(name,document.createTextNode(value));nodes.push(node);}
  }
  if(p.energy && p.energy!=='any')nodes.push(tag(`Energy · ${p.energy}`,'analysis-tag'));
  if(!nodes.length)nodes.push(tag('沒有明確標籤，使用歌曲庫探索','analysis-tag'));
  container.replaceChildren(...nodes);
}
function coverKey(data){return `${data.song.id}|${data.imagePrompt}`;}
function setCoverImage(dataURI){
  const image=byId('cover-ai-image');
  image.src=dataURI;image.hidden=false;
  byId('cover').classList.add('has-ai-image');
  const link=byId('download-cover');link.href=dataURI;link.hidden=false;
  byId('cover-caption').textContent='本圖由 Cloudflare Workers AI 的 FLUX.1 Schnell 實際生成，不是原唱片封面。';
  byId('cover-image-status').textContent='✓ 原創 AI 封面已完成';
}
function resetCover(){
  const image=byId('cover-ai-image');image.hidden=true;image.removeAttribute('src');
  byId('cover').classList.remove('has-ai-image');
  byId('download-cover').hidden=true;
  byId('cover-caption').textContent='這是 CSS 黑膠示意圖；按下「生成原創 AI 封面」才會真正呼叫圖像模型。';
  byId('cover-image-status').textContent=state.imageAvailable?'每張封面只在按下按鈕時生成，避免浪費配額。':'圖片功能尚未啟用，請檢查 Cloudflare AI 綁定。';
}
function render(data,scroll=true){
  const s=data.song;
  byId('song-name').textContent=s.title;byId('artist').textContent=s.artist;
  byId('tags').replaceChildren(...[...s.genre,...s.mood.slice(0,2)].map(x=>tag(x)));
  const sources={llm:'LIVE LLM GENERATION',rules:'RULE-BASED / NO LLM CALL',fallback:'LLM LIMIT / RULE BACKUP'};
  const source=sources[data.textSource]||'RULE-BASED / NO LLM CALL';
  byId('result-source').textContent=source;
  byId('review-source').textContent=data.textSource==='llm'?'GENERATED BY LLM':'RULE-BASED TEXT';
  byId('analysis-source').textContent='LOCAL TAG PARSING (0 LLM CALLS)';
  byId('score').textContent=data.matchScore===null?'SURPRISE PICK':`標籤相似度 ${data.matchScore}%`;
  byId('review-text').textContent=data.review;byId('reason-text').textContent=data.reason;
  byId('prompt-text').textContent=data.imagePrompt;
  byId('analysis-explanation').textContent=data.analysis?.explanation||'依本地標籤進行規則式匹配。';drawTags(data.analysis||{});
  const palette=s.color_palette||[];
  for(let i=0;i<3;i++)if(/^#[a-fA-F0-9]{6}$/.test(palette[i]||''))byId('cover').style.setProperty(`--tone${i+1}`,palette[i]);
  byId('youtube-link').href=`https://www.youtube.com/watch?v=${encodeURIComponent(s.youtube_id)}`;
  const iframe=document.createElement('iframe');iframe.title=`${s.artist} - ${s.title} YouTube 播放器`;
  iframe.src=`https://www.youtube-nocookie.com/embed/${encodeURIComponent(s.youtube_id)}?rel=0`;
  iframe.loading='eager';iframe.referrerPolicy='strict-origin-when-cross-origin';
  iframe.setAttribute('allow','accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture; web-share');iframe.setAttribute('allowfullscreen','');
  byId('player').replaceChildren(iframe);
  byId('results').hidden=false;
  state.lastResult=data;state.previousId=s.id;
  resetCover();
  const previousCover=covers.get(coverKey(data));if(previousCover)setCoverImage(previousCover);
  byId('generate-cover').disabled=!state.imageAvailable;
  byId('replay-btn').disabled=false;
  if(scroll)byId('results').scrollIntoView({behavior:window.matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth',block:'start'});
}
function setWorking(v){state.working=v;for(const id of ['recommend-btn','random-btn','again-btn'])byId(id).disabled=v||!state.aiAvailable;}
function cacheKey(action,mood,previousId,useLLM){return `indie-v3:${action}:${mood.toLowerCase()}:${previousId||''}:${useLLM?'llm':'rules'}`;}
async function run(action){
  if(state.working)return;
  if(!state.aiAvailable){feedback('請先完成 Worker 部署和 REQUEST_LIMITER 設定。',true);return;}
  const mood=byId('mood-text').value.trim();
  if(action==='mood'&&!mood){feedback('請先輸入心情，或使用隨機抽歌。',true);byId('mood-text').focus();return;}
  if(!state.songs.length){feedback('歌曲資料庫尚未載入。',true);return;}
  const useLLM=byId('use-llm').checked&&state.llmAvailable;
  const key=cacheKey(action,mood,state.previousId,useLLM);
  setWorking(true);state.lastAction=action;
  feedback(useLLM?'正在以 1 次 Groq 請求產生微型樂評與圖片 Prompt……':'省額度模式：不呼叫 Groq，使用本地標籤配對歌曲……');
  try {
    let data=null;
    // 只快取成功的 LLM 文字回應，以免重複展示時再次花費 Token。
    if(useLLM){try{data=JSON.parse(sessionStorage.getItem(key)||'null');}catch{}}
    const cacheHit=!!data;
    if(!data){
      const response=await fetch(`${apiBase}/recommend`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({mode:action,mood,previousId:state.previousId,useLLM})});
      try{data=await response.json();}catch{throw new Error('API 回應不是 JSON，請查看 Worker Logs。');}
      if(!response.ok)throw new Error(data.error||`推薦服務錯誤 HTTP ${response.status}`);
      if(useLLM && data.textSource==='llm'){
        try{sessionStorage.setItem(key,JSON.stringify(data));}catch{}
      }
    }
    render(data);
    if(data.warning)feedback(data.warning,true);
    else if(cacheHit)feedback('已讀取本次瀏覽器快取，沒有再次消耗 Groq 額度。');
    else if(data.textSource==='llm')feedback('完成！樂評與圖片 Prompt 是 Groq LLM 即時生成，情緒標籤使用規則分析。');
    else feedback('完成！本次不消耗 Groq 額度；你仍可單獨生成真正的 AI 封面。');
  }catch(e){feedback(e?.message||'推薦失敗，請稍後再試。',true);}
  finally{setWorking(false);}
}
async function generateCover(){
  const data=state.lastResult;
  if(!data || !state.imageAvailable || state.coverWorking)return;
  const key=coverKey(data);
  if(covers.has(key)){setCoverImage(covers.get(key));return;}
  state.coverWorking=true;byId('generate-cover').disabled=true;
  byId('cover-image-status').textContent='FLUX.1 Schnell 正在繪製封面，請勿連續送出……';
  try{
    const res=await fetch(`${apiBase}/cover`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({songId:data.song.id,imagePrompt:data.imagePrompt})});
    let payload;try{payload=await res.json();}catch{throw new Error('圖片服務回傳格式錯誤，請查看 Cloudflare Logs。');}
    if(!res.ok)throw new Error(payload.error||`圖片生成失敗（HTTP ${res.status}）`);
    if(typeof payload.dataURI!=='string'||!payload.dataURI.startsWith('data:image/jpeg;base64,'))throw new Error('圖片內容格式異常。');
    covers.set(key,payload.dataURI);
    // 僅保留少量當頁圖片，避免記憶體持續成長。
    if(covers.size>4)covers.delete(covers.keys().next().value);
    setCoverImage(payload.dataURI);
  }catch(e){byId('cover-image-status').textContent=e?.message||'圖片生成失敗，請稍後再試。';}
  finally{state.coverWorking=false;byId('generate-cover').disabled=!state.imageAvailable;}
}
async function init(){
  try{
    const r=await fetch('./data/songs.json',{cache:'no-store'});
    if(!r.ok)throw new Error('歌曲資料無法載入');
    const songs=await r.json();if(!Array.isArray(songs)||!songs.length)throw new Error('資料庫格式錯誤');
    state.songs=songs;byId('library-count').textContent=songs.length;
  }catch{feedback('網站歌曲資料載入失敗，請確認 docs/data/songs.json。',true);}
  if(!apiBase||!/^https:\/\/[^/]+$/.test(apiBase)||apiBase.includes('REPLACE')){
    byId('connection-status').textContent='◌ Worker 尚未連接';feedback('請在 docs/config.js 填入實際 Cloudflare Worker 網址。',true);return;
  }
  try{
    const r=await fetch(`${apiBase}/status`,{signal:AbortSignal.timeout(8000)});
    if(!r.ok)throw new Error('Worker 尚未就緒');
    const data=await r.json();
    if(data.version!=='3.0')throw new Error('目前仍是舊版 Worker，請更新 worker/index.mjs 並重新部署。');
    state.aiAvailable=!!data.recommendReady;
    state.llmAvailable=!!data.llmReady;
    state.imageAvailable=!!data.imageReady;
    byId('connection-status').textContent=state.aiAvailable?`✦ Worker 已連線 · 圖片${state.imageAvailable?'可用':'待設定'}`:'△ Worker 設定尚未完成';
    byId('use-llm').disabled=!state.llmAvailable;
    byId('generate-cover').disabled=!state.imageAvailable;
    if(!state.llmAvailable)byId('use-llm').checked=false;
    byId('image-service-status').textContent=state.imageAvailable?'✦ FLUX 圖片模型已連線':'△ 尚未設定 AI 或 COVER_LIMITER 綁定';
    const message=!state.aiAvailable?'缺少 REQUEST_LIMITER 或 ALLOWED_ORIGIN，請檢查 Cloudflare 設定。':
      !state.imageAvailable?'推薦功能可用；但還需要在 wrangler.jsonc 綁定 Workers AI 與 COVER_LIMITER。':
      '前後端已連線！預設使用省 Groq 額度模式，按「生成原創 AI 封面」才能產生圖片。';
    feedback(message,!state.aiAvailable);setWorking(false);
  }catch(e){byId('connection-status').textContent='◌ AI 無法連線';feedback(e?.message||'無法連接 Worker，請檢查 config.js 和最新部署。',true);}
}
for(const id of ['recommend-btn','random-btn','again-btn','generate-cover','replay-btn'])byId(id).disabled=true;
byId('recommend-btn').addEventListener('click',()=>run('mood'));
byId('random-btn').addEventListener('click',()=>run('random'));
byId('again-btn').addEventListener('click',()=>run(state.lastAction));
byId('replay-btn').addEventListener('click',()=>{if(state.lastResult){render(state.lastResult,false);feedback('重播上次結果：0 次 Groq 請求、0 次圖片生成。');}});
byId('generate-cover').addEventListener('click',generateCover);
byId('mood-text').addEventListener('input',()=>{byId('char-count').textContent=`${byId('mood-text').value.length} / 220`;});
for(const chip of document.querySelectorAll('[data-mood]'))chip.addEventListener('click',()=>{byId('mood-text').value=chip.dataset.mood;byId('mood-text').dispatchEvent(new Event('input'));feedback('已填入心情，按下「依心情找歌」。');});
byId('copy-prompt').addEventListener('click',async()=>{
  const value=byId('prompt-text').textContent;
  try{await navigator.clipboard.writeText(value);byId('copy-prompt').textContent='✓ 已複製';}catch{byId('copy-prompt').textContent='請手動選取文字複製';}
  setTimeout(()=>{byId('copy-prompt').textContent='複製 Prompt ⧉';},1800);
});
init();
